/*
 * 3DS VR wire protocol, shared by the console app (C, devkitARM) and the
 * PC streamer (C++, MSVC). Everything is UDP, little-endian, packed.
 *
 *   console  --HELLO (broadcast, 2 Hz)-------------------->  streamer
 *   console  <-PAIR_STATUS (code to show) or CONFIG--------   streamer
 *   console  --TRACKING (100 Hz) / SETTINGS / KEYFRAME_REQ->  streamer
 *   console  <-VIDEO fragments / AUDIO / CONFIG (1 Hz)------   streamer
 *
 * See docs/protocol.md for the full description.
 */
#pragma once
#include <stdint.h>

#define VR3DS_MAGIC            0x52564433u /* "3DVR" */
#define VR3DS_PROTOCOL_VERSION 1

#define VR3DS_PORT_STREAMER 39630 /* the PC listens here */
#define VR3DS_PORT_CONSOLE  39631 /* the console listens here */

#define VR3DS_MAX_DATAGRAM  1400
#define VR3DS_MAX_FRAME     (256 * 1024)
#define VR3DS_NAME_LEN      32

#define VR3DS_AUDIO_RATE    32000
#define VR3DS_AUDIO_FRAMES  512 /* stereo frames per AUDIO packet (16 ms) */

enum Vr3dsPacketType {
	VR3DS_PKT_HELLO        = 1,  /* console -> PC (broadcast) */
	VR3DS_PKT_PAIR_STATUS  = 2,  /* PC -> console */
	VR3DS_PKT_CONFIG       = 3,  /* PC -> console */
	VR3DS_PKT_TRACKING     = 4,  /* console -> PC */
	VR3DS_PKT_SETTINGS     = 5,  /* console -> PC */
	VR3DS_PKT_VIDEO        = 6,  /* PC -> console */
	VR3DS_PKT_AUDIO        = 7,  /* PC -> console */
	VR3DS_PKT_KEYFRAME_REQ = 8,  /* console -> PC */
	VR3DS_PKT_BYE          = 9,  /* both ways */
};

/* Same values as libctru's CFG_SystemModel. */
enum Vr3dsModel {
	VR3DS_MODEL_3DS      = 0,
	VR3DS_MODEL_3DSXL    = 1,
	VR3DS_MODEL_NEW3DS   = 2,
	VR3DS_MODEL_2DS      = 3,
	VR3DS_MODEL_NEW3DSXL = 4,
	VR3DS_MODEL_NEW2DSXL = 5,
	VR3DS_MODEL_COUNT
};

#define VR3DS_CAP_HW_H264 0x01 /* New 3DS family: hardware H.264 decoder */
#define VR3DS_CAP_STEREO  0x02 /* has an autostereoscopic top screen */

enum Vr3dsCodec {
	VR3DS_CODEC_H264 = 1, /* Annex-B, constrained baseline, one slice per frame */
	VR3DS_CODEC_JPEG = 2, /* baseline JPEG, 4:2:0 */
};

enum Vr3dsPairState {
	VR3DS_PAIR_PENDING  = 1, /* waiting for the user to click "Pair" on the PC */
	VR3DS_PAIR_REJECTED = 2,
};

/* Xbox 360 button bits (same as XINPUT_GAMEPAD_*). */
#define VR3DS_BTN_DPAD_UP    0x0001
#define VR3DS_BTN_DPAD_DOWN  0x0002
#define VR3DS_BTN_DPAD_LEFT  0x0004
#define VR3DS_BTN_DPAD_RIGHT 0x0008
#define VR3DS_BTN_START      0x0010
#define VR3DS_BTN_BACK       0x0020
#define VR3DS_BTN_LTHUMB     0x0040
#define VR3DS_BTN_RTHUMB     0x0080
#define VR3DS_BTN_LSHOULDER  0x0100
#define VR3DS_BTN_RSHOULDER  0x0200
#define VR3DS_BTN_GUIDE      0x0400
#define VR3DS_BTN_A          0x1000
#define VR3DS_BTN_B          0x2000
#define VR3DS_BTN_X          0x4000
#define VR3DS_BTN_Y          0x8000

#define VR3DS_BATT_CHARGING 0x01
#define VR3DS_BATT_ADAPTER  0x02

#define VR3DS_FRAME_KEY 0x01

#pragma pack(push, 1)

typedef struct {
	uint32_t magic;
	uint8_t version;
	uint8_t type;
	uint16_t reserved;
} Vr3dsHeader;

/* What the console would like to receive. */
typedef struct {
	uint8_t stereo;        /* 1: both eyes, 0: one centred view */
	uint8_t fps;           /* 20, 30 or 60 */
	uint16_t bitrateKbps;
	float tanX, tanY;      /* half-FOV tangents of the visible top screen */
	uint16_t heightCm;     /* the player's height: places the head in SteamVR */
	uint16_t reserved;
} Vr3dsStreamSettings;

typedef struct {
	Vr3dsHeader h;
	uint64_t consoleId;
	uint64_t token;        /* secret generated by the console, remembered by paired PCs */
	uint8_t model;         /* Vr3dsModel */
	uint8_t caps;          /* VR3DS_CAP_* */
	uint8_t appVersion[3];
	uint8_t reserved;
	char name[VR3DS_NAME_LEN]; /* console owner nickname, UTF-8 */
	Vr3dsStreamSettings settings;
} Vr3dsHello;

typedef struct {
	Vr3dsHeader h;
	uint8_t state;         /* Vr3dsPairState */
	uint8_t reserved;
	uint16_t code;         /* 0000-9999, shown on both sides */
	char pcName[VR3DS_NAME_LEN];
} Vr3dsPairStatus;

typedef struct {
	Vr3dsHeader h;
	uint32_t sessionId;
	uint16_t configId;     /* changes every time the stream format changes */
	uint8_t codec;         /* Vr3dsCodec */
	uint8_t stereo;
	uint16_t eyeWidth;     /* eyes are stacked vertically: left on top */
	uint16_t eyeHeight;
	uint8_t fps;
	uint8_t reserved;
	uint16_t bitrateKbps;
	float encTanX, encTanY; /* half-FOV tangents covered by each encoded eye image */
	char pcName[VR3DS_NAME_LEN];
} Vr3dsConfig;

typedef struct {
	uint16_t buttons;      /* VR3DS_BTN_* */
	uint8_t leftTrigger, rightTrigger;
	int16_t lx, ly, rx, ry;
} Vr3dsGamepad;

typedef struct {
	Vr3dsHeader h;
	uint32_t seq;
	float qw, qx, qy, qz;  /* head orientation, SteamVR axes (+X right, +Y up, -Z forward) */
	Vr3dsGamepad pad;
	uint8_t stereoStrength; /* 3D slider, 0-255 */
	uint8_t battery;        /* percent */
	uint8_t batteryFlags;   /* VR3DS_BATT_* */
	uint8_t wifi;           /* 0-3 bars */
	uint32_t shownFrameId;  /* last frame put on screen */
	uint64_t shownFrameTs;  /* its timestamp, echoed back for latency stats */
	uint32_t shownFrameAgeUs; /* time between its reception and now */
	uint32_t framesDecoded;
	uint32_t framesDropped;
} Vr3dsTracking;

typedef struct {
	Vr3dsHeader h;
	uint32_t seq;
	Vr3dsStreamSettings settings;
} Vr3dsSettingsPacket;

typedef struct {
	Vr3dsHeader h;
	uint32_t frameId;      /* consecutive within a config */
	uint16_t configId;
	uint16_t fragIndex;
	uint16_t fragCount;
	uint8_t flags;         /* VR3DS_FRAME_* */
	uint8_t reserved;
	uint32_t frameSize;
	uint64_t timestampUs;  /* PC clock, echoed in TRACKING */
	float qw, qx, qy, qz;  /* head orientation this frame was rendered with */
} Vr3dsVideoHeader;

#define VR3DS_VIDEO_PAYLOAD (VR3DS_MAX_DATAGRAM - (int)sizeof(Vr3dsVideoHeader))

typedef struct {
	Vr3dsHeader h;
	uint32_t seq;
	uint16_t frames;       /* stereo frames in this packet */
	int16_t predictor[2];  /* IMA-ADPCM state at the start of the packet (L, R) */
	uint8_t stepIndex[2];
	/* followed by `frames` bytes: low nibble = left, high nibble = right */
} Vr3dsAudioHeader;

typedef struct {
	Vr3dsHeader h;
	uint16_t configId;
} Vr3dsKeyframeRequest;

#pragma pack(pop)

static inline void vr3ds_header(Vr3dsHeader* h, uint8_t type) {
	h->magic = VR3DS_MAGIC;
	h->version = VR3DS_PROTOCOL_VERSION;
	h->type = type;
	h->reserved = 0;
}

static inline int vr3ds_check(const void* data, int len, int minLen) {
	const Vr3dsHeader* h = (const Vr3dsHeader*)data;
	return len >= minLen && len >= (int)sizeof(Vr3dsHeader) && h->magic == VR3DS_MAGIC &&
		   h->version == VR3DS_PROTOCOL_VERSION;
}
